import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'firebase_options.dart'; // Generated by: flutterfire configure

const red = Color(0xFFF43F5E);
const bg = Color(0xFF09090C);

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const RedPulseApp());
}

class RedPulseApp extends StatelessWidget {
  const RedPulseApp({super.key});
  @override
  Widget build(BuildContext context) => MaterialApp(
    debugShowCheckedModeBanner: false,
    title: 'RED PULSE',
    theme: ThemeData.dark().copyWith(
      scaffoldBackgroundColor: bg,
      colorScheme: ColorScheme.fromSeed(seedColor: red, brightness: Brightness.dark),
      inputDecorationTheme: InputDecorationTheme(
        filled: true, fillColor: const Color(0xFF151117),
        border: OutlineInputBorder(borderRadius: BorderRadius.circular(13), borderSide: const BorderSide(color: Colors.white12)),
        enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(13), borderSide: const BorderSide(color: Colors.white12)),
      ),
    ),
    home: const AuthGate(),
  );
}

class AuthGate extends StatelessWidget {
  const AuthGate({super.key});
  @override
  Widget build(BuildContext context) => StreamBuilder<User?>(
    stream: FirebaseAuth.instance.authStateChanges(),
    builder: (context, snapshot) {
      if (snapshot.connectionState == ConnectionState.waiting) {
        return const Scaffold(body: Center(child: CircularProgressIndicator(color: red)));
      }
      if (snapshot.data != null) return const HomeScreen();
      return const AuthScreen();
    },
  );
}

class AuthScreen extends StatefulWidget {
  const AuthScreen({super.key});
  @override
  State<AuthScreen> createState() => _AuthScreenState();
}

class _AuthScreenState extends State<AuthScreen> {
  final _form = GlobalKey<FormState>();
  final _name = TextEditingController();
  final _email = TextEditingController();
  final _password = TextEditingController();
  bool _signup = false, _showPassword = false, _busy = false;
  String? _message;

  @override
  void dispose() { _name.dispose(); _email.dispose(); _password.dispose(); super.dispose(); }

  String _error(FirebaseAuthException e) {
    switch (e.code) {
      case 'invalid-email': return 'Please enter a valid email address.';
      case 'weak-password': return 'Use a stronger password (at least 6 characters).';
      case 'email-already-in-use': return 'An account already exists for this email.';
      case 'invalid-credential': return 'Email or password is incorrect.';
      case 'too-many-requests': return 'Too many attempts. Try again later.';
      default: return 'Something went wrong. Please try again.';
    }
  }

  Future<void> _submit() async {
    if (!_form.currentState!.validate()) return;
    setState(() { _busy = true; _message = null; });
    try {
      if (_signup) {
        final cred = await FirebaseAuth.instance.createUserWithEmailAndPassword(
          email: _email.text.trim(), password: _password.text,
        );
        if (_name.text.trim().isNotEmpty) await cred.user?.updateDisplayName(_name.text.trim());
        await cred.user?.sendEmailVerification();
        setState(() => _message = 'Account created. Verify your email using the link sent to your inbox.');
      } else {
        await FirebaseAuth.instance.signInWithEmailAndPassword(
          email: _email.text.trim(), password: _password.text,
        );
      }
    } on FirebaseAuthException catch (e) {
      setState(() => _message = _error(e));
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  Future<void> _reset() async {
    if (_email.text.trim().isEmpty) { setState(() => _message = 'Enter your email address first.'); return; }
    try {
      await FirebaseAuth.instance.sendPasswordResetEmail(email: _email.text.trim());
      setState(() => _message = 'Password reset link sent. Check your inbox.');
    } on FirebaseAuthException catch (e) { setState(() => _message = _error(e)); }
  }

  @override
  Widget build(BuildContext context) => Scaffold(
    body: Center(child: SingleChildScrollView(padding: const EdgeInsets.all(22), child: ConstrainedBox(
      constraints: const BoxConstraints(maxWidth: 440),
      child: Container(
        padding: const EdgeInsets.all(25),
        decoration: BoxDecoration(
          borderRadius: BorderRadius.circular(27),
          border: Border.all(color: Colors.white12),
          gradient: const LinearGradient(colors: [Color(0xFF25131C), Color(0xFF111015)]),
          boxShadow: [BoxShadow(color: red.withOpacity(.12), blurRadius: 45)],
        ),
        child: Form(key: _form, child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
          Row(children: [
            Container(width: 49, height: 49, alignment: Alignment.center,
              decoration: BoxDecoration(borderRadius: BorderRadius.circular(15), gradient: const LinearGradient(colors: [red, Color(0xFF8F092B)])),
              child: const Text('RP', style: TextStyle(fontWeight: FontWeight.w900, fontSize: 18))),
            const SizedBox(width: 13),
            const Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              Text('RED PULSE', style: TextStyle(fontWeight: FontWeight.w900, letterSpacing: 2, fontSize: 18)),
              Text('CONNECT WITHOUT LIMITS', style: TextStyle(color: Color(0xFFF58BA0), fontSize: 9, letterSpacing: 1.5)),
            ]),
          ]),
          const SizedBox(height: 34),
          Text(_signup ? 'JOIN THE NETWORK' : 'WELCOME BACK', style: const TextStyle(color: Color(0xFFF58BA0), letterSpacing: 2, fontSize: 10, fontWeight: FontWeight.bold)),
          const SizedBox(height: 8),
          Text(_signup ? 'Create account' : 'Sign in', style: const TextStyle(fontSize: 32, fontWeight: FontWeight.w800)),
          const SizedBox(height: 7),
          Text(_signup ? 'Create your RED PULSE account.' : 'Your conversations are waiting.', style: const TextStyle(color: Colors.white60)),
          const SizedBox(height: 25),
          if (_signup) ...[
            const Text('Display name'), const SizedBox(height: 7),
            TextFormField(controller: _name, decoration: const InputDecoration(hintText: 'Your name')),
            const SizedBox(height: 17),
          ],
          const Text('Email address'), const SizedBox(height: 7),
          TextFormField(controller: _email, keyboardType: TextInputType.emailAddress,
            decoration: const InputDecoration(hintText: 'you@example.com'),
            validator: (v) => v == null || !v.contains('@') ? 'Enter a valid email address.' : null),
          const SizedBox(height: 17),
          const Text('Password'), const SizedBox(height: 7),
          TextFormField(controller: _password, obscureText: !_showPassword,
            decoration: InputDecoration(hintText: 'At least 6 characters', suffixIcon: IconButton(
              onPressed: () => setState(() => _showPassword = !_showPassword),
              icon: Icon(_showPassword ? Icons.visibility_off : Icons.visibility))),
            validator: (v) => v == null || v.length < 6 ? 'Password must be at least 6 characters.' : null),
          if (!_signup) Align(alignment: Alignment.centerRight, child: TextButton(onPressed: _reset, child: const Text('Forgot password?', style: TextStyle(color: Color(0xFFFF8299))))),
          const SizedBox(height: 12),
          FilledButton(
            style: FilledButton.styleFrom(backgroundColor: red, padding: const EdgeInsets.symmetric(vertical: 16)),
            onPressed: _busy ? null : _submit,
            child: Text(_busy ? 'Please wait…' : _signup ? 'Create account  →' : 'Sign in  →'),
          ),
          if (_message != null) ...[
            const SizedBox(height: 15),
            Text(_message!, style: const TextStyle(color: Color(0xFFFFB5C3))),
          ],
          const SizedBox(height: 17),
          TextButton(
            onPressed: () => setState(() { _signup = !_signup; _message = null; }),
            child: Text(_signup ? 'Already have an account? Sign in' : 'New to RED PULSE? Create account', style: const TextStyle(color: Color(0xFFFF8299))),
          ),
        ])),
      ),
    ))),
  );
}

class HomeScreen extends StatelessWidget {
  const HomeScreen({super.key});
  @override
  Widget build(BuildContext context) {
    final user = FirebaseAuth.instance.currentUser;
    return Scaffold(
      appBar: AppBar(title: const Text('RED PULSE', style: TextStyle(color: red, fontWeight: FontWeight.w900, letterSpacing: 2)),
        actions: [IconButton(onPressed: () => FirebaseAuth.instance.signOut(), icon: const Icon(Icons.logout))]),
      body: Center(child: Column(mainAxisSize: MainAxisSize.min, children: [
        const Icon(Icons.bolt, color: red, size: 58),
        const Text('Welcome to RED PULSE', style: TextStyle(fontSize: 23, fontWeight: FontWeight.bold)),
        const SizedBox(height: 8),
        Text(user?.email ?? '', style: const TextStyle(color: Colors.white60)),
        const SizedBox(height: 14),
        Text(user?.emailVerified == true ? 'Email verified' : 'Please verify your email', style: const TextStyle(color: red)),
      ])),
    );
  }
}
